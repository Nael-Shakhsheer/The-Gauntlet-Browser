const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const sandbox={window:{}};vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('static/camera.js','utf8'),sandbox);
const {create,scrolls}=sandbox.window.GauntletCamera;
const room={code:'CAM',stage:1,phase:'combat',adventure:{area:'road'},areaSize:[1800,900],you:'p',players:[{id:'p',x:1100,y:600}]};
const c=create();let v=c.frame(room,1280,700,1000);
assert.equal(v.large,true);assert.equal(v.overview,false);
assert.ok(v.cx>900);assert.ok(v.zoom>Math.min(1280/1800,700/900));
room.players[0].x=1300;v=c.frame(room,1280,700,1016);assert.equal(v.cx,1300);
const rect={left:14,top:9,width:1280,height:700};
for(const [x,y] of [[1300,650],[1790,880],[25,25]]){
  const p=c.screenPoint(x,y,rect),q=c.worldPoint(p.x,p.y,rect);
  assert.ok(Math.abs(q.x-x)<.0001 && Math.abs(q.y-y)<.0001,'Target coordinates round-trip through a panned camera');
}
c.press(1100);for(let t=1100;t<1700;t+=16)v=c.frame(room,1280,700,t);
assert.equal(v.overview,true);assert.ok(Math.abs(v.cx-900)<1);
assert.ok(v.w*v.zoom<=v.cw+1 && v.h*v.zoom<=v.ch+1,'Whole area fits without cropping');
c.release(1700);v=c.frame(room,1280,700,1716);assert.equal(v.overview,false);
c.press(1800,2);c.release(1870,3);v=c.frame(room,1280,700,1880);assert.equal(v.overview,true,'Another finger cannot release the hold');
c.release(1880,2);v=c.frame(room,1280,700,2000);assert.equal(v.overview,true,'Quick tap previews for three seconds');
v=c.frame(room,1280,700,5000);assert.equal(v.overview,false,'Tap preview expires');
c.peek(5100);c.clear();v=c.frame(room,1280,700,5116);assert.equal(v.overview,false,'Focus loss clears overview');
c.peek(5200);room.adventure.area='crossroads';room.areaSize=[1920,1080];v=c.frame(room,1280,700,5216);assert.equal(v.overview,false,'Travel resets view state');
room.adventure.area='camp';room.areaSize=[960,540];v=c.frame(room,1280,700,5300);assert.equal(v.large,false);
assert.equal(v.cx,480);assert.equal(v.cy,270);assert.equal(v.zoom,700/540,'Compact rooms stay fully visible with equal X/Y scaling');
room.adventure.area='road';room.areaSize=[1800,900];v=c.frame(room,390,640,5400);assert.equal(v.large,true);
assert.ok(390/v.zoom<960,'Portrait follow view keeps the hero readable');
c.peek(5416);for(let t=5416;t<6100;t+=16)v=c.frame(room,390,640,t);
assert.ok(v.w*v.zoom<=390+1 && v.h*v.zoom<=640+1,'Portrait overview shows the complete field');
room.townInterior='inn';assert.equal(scrolls(room),false);room.townInterior=null;room.phase='puzzle';assert.equal(scrolls(room),false);
console.log('Camera follow, bounds, targeting, hold/tap expiry, touch multi-pointer, scene reset and compact/aspect views: OK');
const {landscapeRequired}=sandbox.window.GauntletCamera;
assert.equal(landscapeRequired(true,true,390,844),true);
assert.equal(landscapeRequired(true,true,844,390),false);
assert.equal(landscapeRequired(false,true,390,844),false,'Lobby remains usable in portrait');
assert.equal(landscapeRequired(true,false,390,844),false,'Narrow desktop windows do not require rotation');
console.log('Mobile gameplay requires landscape; desktop and lobby remain unaffected: OK');
