const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const box={window:{}};vm.runInNewContext(fs.readFileSync('static/state-cache.js','utf8'),box);
const api=box.window.GauntletStateCache;
const old={code:'TEST',you:'one',catalogVersion:'v1',classes:{Knight:1},difficulties:{},skills:{},abilityOptions:{},heroSkillsRevision:'h1',heroSkills:{hero:'Knight'},mana:50,enemies:[1]};
assert.ok(api.query(old,{room:'TEST',player:'one'}).includes('catalog=v1'));
assert.equal(api.query(old,{room:'OTHER',player:'one'}),'');
assert.equal(api.query(old,{room:'TEST',player:'two'}),'');
const fresh={code:'TEST',you:'one',catalogVersion:'v1',heroSkillsRevision:'h1',mana:19,enemies:[2]};
api.merge(fresh,old);assert.equal(fresh.heroSkills,old.heroSkills);assert.equal(fresh.classes,old.classes);assert.equal(fresh.mana,19);assert.deepEqual(fresh.enemies,[2]);
assert.throws(()=>api.merge({...fresh,classes:undefined,code:'OTHER',abilityOptions:undefined},old));
const missing={code:'TEST',you:'one',catalogVersion:'v2'};assert.throws(()=>api.merge(missing,old));
assert.throws(()=>api.merge({code:'TEST',you:'two',catalogVersion:'v1'},old));
const updated={...fresh,heroSkillsRevision:'h2',heroSkills:{hero:'Healer'}};api.merge(updated,old);assert.equal(updated.heroSkills.hero,'Healer');
const wave={...fresh,heroSkillsRevision:null,heroSkills:null};api.merge(wave,old);assert.equal(wave.heroSkills,null);
console.log('Revisioned catalog/skills merge: fresh live fields, stale/build/identity rejection, class and mode changes pass.');
